// Emits SQL that seeds curated/daily/tutorial dungeons with the same ids the client uses.
import { CURATED } from "../lib/game/levels";
import { layoutHash } from "../lib/game/dungeon";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ["-- Curated dungeons (generated by scripts/seed-sql.ts)", "begin;"];
CURATED.forEach((d, i) => {
  lines.push(
    `insert into public.dungeons (id, owner_id, kind, title, description, theme, difficulty, sort_order) values (${q(d.id)}, null, ${q(d.kind)}, ${q(d.title)}, ${q(d.description)}, ${d.layout.theme}, ${d.difficulty && d.difficulty !== "Unrated" ? q(d.difficulty) : "null"}, ${i}) on conflict (id) do update set title = excluded.title, description = excluded.description, theme = excluded.theme, difficulty = excluded.difficulty, sort_order = excluded.sort_order;`,
    `insert into public.dungeon_versions (id, dungeon_id, version, layout, layout_hash) values (${q(d.versionId)}, ${q(d.id)}, 1, ${q(JSON.stringify(d.layout))}::jsonb, ${q(layoutHash(d.layout))}) on conflict (id) do nothing;`,
    `update public.dungeons set current_version_id = ${q(d.versionId)} where id = ${q(d.id)};`,
  );
});
lines.push("commit;");
console.log(lines.join("\n"));
